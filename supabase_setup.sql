-- Run this SQL in Supabase SQL Editor.
create table if not exists public.excel_uploads (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  file_name text not null,
  storage_path text not null,
  file_size bigint,
  created_at timestamptz not null default now()
);

alter table public.excel_uploads enable row level security;

create policy "Users can view their own uploads"
on public.excel_uploads for select
using (auth.uid() = user_id);

create policy "Users can insert their own uploads"
on public.excel_uploads for insert
with check (auth.uid() = user_id);

-- Create a private Storage bucket named: excel-files
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('excel-files', 'excel-files', false, 52428800,
  array['application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
        'application/vnd.ms-excel',
        'text/csv'])
on conflict (id) do nothing;

create policy "Users can upload into their own folder"
on storage.objects for insert to authenticated
with check (bucket_id = 'excel-files' and (storage.foldername(name))[1] = auth.uid()::text);

create policy "Users can read their own files"
on storage.objects for select to authenticated
using (bucket_id = 'excel-files' and (storage.foldername(name))[1] = auth.uid()::text);
